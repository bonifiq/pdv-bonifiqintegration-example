test('cancelamento parcial envia produtos e valor com o casing do contrato', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Cenário guiado').selectOption('no-rewards')
  await page.getByRole('button', { name: 'OK' }).click()
  await page.getByRole('button', { name: /Calça Jeans/ }).click()
  await page.getByRole('button', { name: /Ir para pagamento/ }).click()
  await page.getByRole('button', { name: /Finalizar venda em dinheiro/ }).click()

  await page.getByLabel('Quantidade de Calça Jeans para cancelar').fill('1')
  await page.getByRole('button', { name: 'Cancelar itens selecionados' }).click()
  await expect(page.getByText('Cancelamento parcial enviado para a BonifiQ.')).toBeVisible()
  await expect(page.getByText('Parcialmente cancelado')).toBeVisible()
  await expect(page.getByText('Cashback ganho nesta venda')).toHaveCount(0)

  await page.getByRole('button', { name: /Ver integração/ }).click()
  const trace = page.locator('.trace-event').filter({ hasText: 'Cancelar parcialmente' })
  await trace.locator('.trace-summary').click()
  const requestBody = trace.locator('pre').first()
  await expect(requestBody).toContainText('"ValueToRefund"')
  await expect(requestBody).toContainText('"CancelKey"')
  await expect(requestBody).toContainText('"Products"')
  await expect(requestBody).toContainText('"OriginalId"')
  await expect(requestBody).not.toContainText('"valueToRefund"')
})

test('confirmação permite cancelar o pedido inteiro', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Cenário guiado').selectOption('no-rewards')
  await page.getByRole('button', { name: 'OK' }).click()
  await page.getByRole('button', { name: /Ir para pagamento/ }).click()
  await page.getByRole('button', { name: /Finalizar venda em dinheiro/ }).click()

  await page.getByRole('button', { name: 'Cancelar pedido inteiro' }).click()

  await expect(page.getByRole('heading', { name: 'Pedido cancelado' })).toBeVisible()
  await expect(page.getByText('Cancelamento enviado para a BonifiQ.')).toBeVisible()
  await expect(page.getByText('Cashback ganho nesta venda')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Cancelar pedido inteiro' })).toBeDisabled()
})
