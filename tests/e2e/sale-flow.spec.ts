import { expect, test } from '@playwright/test'

test('brinde aparece no carrinho e é estornado ao voltar', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Cenário guiado').selectOption('gift')
  await page.getByRole('button', { name: 'OK' }).click()
  await page.getByRole('button', { name: /Ir para pagamento/ }).click()
  await page.getByRole('button', { name: /Escolher benefício/ }).click()
  await page.getByRole('button', { name: /Caneca BonifiQ de brinde/ }).click()
  await page.getByRole('button', { name: 'Confirmar e resgatar' }).click()
  const token = await page.locator('.received-token strong').last().textContent()
  await page.getByLabel('Código de validação').fill(token || '')
  await page.getByRole('button', { name: 'Validar' }).click()
  await expect(page.getByText('Benefício aplicado')).toBeVisible()
  await expect(page.getByText('Caneca BonifiQ', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Editar seleção/ }).click()
  await expect(page.getByText('Caneca BonifiQ', { exact: true })).toHaveCount(0)
})

test('cenário sem OTP resgata e registra pedido com trace', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Cenário guiado').selectOption('no-validation')
  await page.getByRole('button', { name: 'OK' }).click()
  await page.getByRole('button', { name: /Ir para pagamento/ }).click()
  await page.getByRole('button', { name: /Escolher benefício/ }).click()
  await page.getByRole('button', { name: /R\$10,00 de desconto/ }).click()
  await page.getByRole('button', { name: 'Confirmar e resgatar' }).click()
  await expect(page.getByRole('heading', { name: /Validação de identidade/ })).toHaveCount(0)
  await expect(page.getByText('Benefício aplicado')).toBeVisible()
  await page.getByRole('button', { name: /Finalizar venda em dinheiro/ }).click()
  await expect(page.getByText('Venda concluída!')).toBeVisible()
  await expect(page.getByText('Cashback ganho nesta venda')).toBeVisible()
  await expect(page.locator('.cashback-earned')).toContainText(/R\$\s*11,99/)
  await expect(page.getByText(/Nova venda em/)).toHaveCount(0)
  await page.getByRole('button', { name: /Ver integração/ }).click()
  await expect(page.getByText('POST /POS/orders', { exact: true })).toBeVisible()
  const orderTrace = page.locator('.trace-event').filter({ hasText: 'Registrar pedido' })
  await orderTrace.locator('.trace-summary').click()
  const requestBody = orderTrace.locator('pre').first()
  await expect(requestBody).toContainText('"OrderTotal"')
  await expect(requestBody).not.toContainText('"orderTotal"')
  await expect(requestBody).toContainText('98765432100')
})

